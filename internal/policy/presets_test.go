func TestPsqlPreset(t *testing.T) {
	expect(t, Allow,
		`psql -c "select 1"`,
		`psql -h db -U app -d main -c "SELECT * FROM users LIMIT 5"`,
		`psql --command="show server_version"`,
		`psql -c "explain select 1"`,
		`psql -c '\dt'`,
		`psql -c '\d users'`,
		"psql -l",
		"psql --version",
	)
	expect(t, Confirm,
		`psql -c "insert into t values (1)"`,
		`psql -c "update t set a = 1"`,
		`psql -c "alter table t add b int"`,
		`psql -c "create table t (a int)"`,
		"psql -f migrate.sql",
		"psql -d main -f migrate.sql",
	)
	expect(t, Deny,
		`psql -c "drop table t"`,
		`psql -c "DROP TABLE t"`,
		`psql -c "delete from t"`,
		`psql -c "truncate t"`,
		`psql -c "select 1; drop table t"`,
		`psql -c "with x as (delete from t returning *) select * from x"`,
		`psql -c "select 1" -c "drop table t"`,
		`psql --command="drop table t"`,
		`psql "--command=drop table t"`,
		`psql -c '\! rm -rf /'`,
		`psql -c '\copy t to x'`,
		`psql -c '\o /tmp/x'`,
		`psql -c "copy t to program 'rm -rf /'"`,
		`psql -c "select pg_terminate_backend(1)"`,
		"psql main",
		"psql < drop.sql",
		"psql <<EOF\ndrop table t;\nEOF",
		"echo 'drop table t' | psql",
	)
}

func TestMysqlPreset(t *testing.T) {
	expect(t, Allow,
		`mysql -e "select 1"`,
		`mysql -h db -u app -e "SHOW TABLES"`,
		`mysql --execute="describe users"`,
		`mariadb -e "select 1"`,
		"mysql --version",
		"mysqladmin status",
	)
	expect(t, Confirm,
		`mysql -e "insert into t values (1)"`,
		`mysql -e "update t set a = 1"`,
		`mysql -e "alter table t add b int"`,
	)
	expect(t, Deny,
		`mysql -e "drop table t"`,
		`mysql -e "DELETE FROM t"`,
		`mysql -e "truncate t"`,
		`mysql -e "select 1; drop database d"`,
		`mysql -e "select * from t into outfile '/tmp/x'"`,
		`mysql -e "select load_file('/etc/passwd')"`,
		`mysql -e "system rm -rf /"`,
		`mysql -e "source x.sql"`,
		"mysql main",
		"mysql < drop.sql",
		"mysqladmin drop main",
		"mysqladmin shutdown",
	)
}
